//! Python bindings: `lean_source_parser._native`.

use lean_source::keywords::Modifier;
use lean_source::pos::LineIndex;
use lean_source::{Parsed, Span};
use pyo3::exceptions::PyValueError;
use pyo3::prelude::*;
use pyo3::types::{PyDict, PyList};
use rayon::prelude::*;

type SpanTuple = (u32, u32, u32, u32, u32, u32);

fn span(src: &[u8], idx: &LineIndex, s: Span) -> SpanTuple {
    let a = idx.pos(src, s.start);
    let b = idx.pos(src, s.end);
    (a.byte, a.line, a.col, b.byte, b.line, b.col)
}

fn slice(src: &[u8], s: Span) -> &str {
    std::str::from_utf8(&src[s.start as usize..s.end as usize]).unwrap_or("")
}

fn decls_to_py<'py>(
    py: Python<'py>,
    src: &[u8],
    parsed: &Parsed,
    file: &str,
    module: &str,
    text: bool,
) -> PyResult<Bound<'py, PyList>> {
    let idx = LineIndex::new(src);
    let out = PyList::empty(py);
    for (i, d) in parsed.decls.iter().enumerate() {
        let o = PyDict::new(py);
        o.set_item("file", file)?;
        o.set_item("module", module)?;
        o.set_item("index", i)?;
        o.set_item("kind", d.kind.as_str())?;
        o.set_item("name", d.name.as_deref())?;
        o.set_item("generated", d.generated)?;
        o.set_item("approximate", d.approximate)?;
        o.set_item("origin", d.origin.map(|s| slice(src, s)))?;
        o.set_item("parent", d.parent)?;
        let mods: Vec<&str> = Modifier::ALL
            .iter()
            .filter(|m| d.modifiers & m.bit() != 0)
            .map(|m| m.name())
            .collect();
        o.set_item("modifiers", mods)?;
        let attrs: Vec<&str> = parsed.attrs[d.attrs.0 as usize..d.attrs.1 as usize]
            .iter()
            .map(|a| slice(src, a.span))
            .collect();
        o.set_item("attributes", attrs)?;
        o.set_item("range", span(src, &idx, d.range))?;
        o.set_item("selection", span(src, &idx, d.selection))?;
        o.set_item("signature", span(src, &idx, d.signature))?;
        o.set_item("type", d.type_.map(|s| span(src, &idx, s)))?;
        o.set_item("body", d.body.map(|s| span(src, &idx, s)))?;
        o.set_item("doc", d.doc.map(|s| span(src, &idx, s)))?;
        if text {
            o.set_item("text", slice(src, d.range))?;
            o.set_item("signature_text", slice(src, d.signature))?;
            o.set_item("type_text", d.type_.map(|s| slice(src, s)))?;
            o.set_item("doc_text", d.doc.map(|s| slice(src, s)))?;
        }
        out.append(o)?;
    }
    Ok(out)
}

/// Parses Lean source text and returns one dict per declaration.
///
/// Spans are tuples `(start_byte, start_line, start_col, end_byte, end_line, end_col)`, with
/// 1-based lines and columns in code points, as Lean reports them. With `text=True` each dict
/// also carries the source of the declaration, its signature, type and doc comment.
#[pyfunction]
#[pyo3(signature = (source, file = "", module = "", text = false))]
fn parse<'py>(
    py: Python<'py>,
    source: &str,
    file: &str,
    module: &str,
    text: bool,
) -> PyResult<Bound<'py, PyList>> {
    let parsed = py.detach(|| lean_source::parse(source.as_bytes()));
    decls_to_py(py, source.as_bytes(), &parsed, file, module, text)
}

/// File name and module name of `path` relative to `root`: `Mathlib/Data/Nat.lean` gives
/// `Mathlib.Data.Nat`.
fn module_of(path: &std::path::Path, root: Option<&std::path::Path>) -> (String, String) {
    let rel = match root {
        Some(r) => path.strip_prefix(r).unwrap_or(path),
        None => path,
    };
    let file = rel.to_string_lossy().into_owned();
    let module = rel
        .with_extension("")
        .components()
        .map(|c| c.as_os_str().to_string_lossy().into_owned())
        .collect::<Vec<_>>()
        .join(".");
    (file, module)
}

/// Parses several files in parallel, without the GIL, as one project: names generated by
/// `to_additive` and `to_dual` are resolved against the other files. Returns one list of
/// declaration dicts per path, in order. Module names are relative to `root` when it is given.
#[pyfunction]
#[pyo3(signature = (paths, root = None, text = false))]
fn parse_files<'py>(
    py: Python<'py>,
    paths: Vec<std::path::PathBuf>,
    root: Option<std::path::PathBuf>,
    text: bool,
) -> PyResult<Bound<'py, PyList>> {
    let results: Vec<std::io::Result<(Vec<u8>, Parsed)>> = py.detach(|| {
        let first: Vec<std::io::Result<(Vec<u8>, Parsed)>> = paths
            .par_iter()
            .map(|p| {
                let src = std::fs::read(p)?;
                let parsed = lean_source::parse(&src);
                Ok((src, parsed))
            })
            .collect();
        if paths.len() < 2 {
            return first;
        }
        // Names that `to_additive` and `to_dual` generate depend on the rest of the project.
        let mut ctx = lean_source::Context::default();
        for (_, parsed) in first.iter().flatten() {
            ctx.add(parsed);
        }
        first
            .into_par_iter()
            .map(|r| {
                r.map(|(src, parsed)| {
                    let uses = parsed.decls.iter().any(|d| d.origin.is_some());
                    if uses {
                        let again = lean_source::parse_in(&src, &ctx);
                        (src, again)
                    } else {
                        (src, parsed)
                    }
                })
            })
            .collect()
    });
    let out = PyList::empty(py);
    for (p, r) in paths.iter().zip(results) {
        let (src, parsed) =
            r.map_err(|e| PyValueError::new_err(format!("{}: {e}", p.display())))?;
        let (file, module) = module_of(p, root.as_deref());
        out.append(decls_to_py(py, &src, &parsed, &file, &module, text)?)?;
    }
    Ok(out)
}

/// Commands of a file: `kind`, `range`, `head` and the namespace in effect.
#[pyfunction]
fn commands<'py>(py: Python<'py>, source: &str) -> PyResult<Bound<'py, PyList>> {
    let src = source.as_bytes();
    let parsed = py.detach(|| lean_source::parse(src));
    let idx = LineIndex::new(src);
    let out = PyList::empty(py);
    for c in &parsed.commands {
        let o = PyDict::new(py);
        o.set_item("kind", c.kind.as_str())?;
        o.set_item("range", span(src, &idx, c.range))?;
        o.set_item("head", slice(src, c.head))?;
        o.set_item("namespace", &parsed.namespaces[c.namespace as usize])?;
        out.append(o)?;
    }
    Ok(out)
}

#[pymodule]
fn _native(m: &Bound<'_, PyModule>) -> PyResult<()> {
    m.add_function(wrap_pyfunction!(parse, m)?)?;
    m.add_function(wrap_pyfunction!(parse_files, m)?)?;
    m.add_function(wrap_pyfunction!(commands, m)?)?;
    Ok(())
}
