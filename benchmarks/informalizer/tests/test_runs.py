"""Tests of the journal, the per-file prompt and the cost scoring."""

from collections import Counter

from openai.types import CompletionUsage

from benchmarks.informalizer.arm_per_file import render_batch, render_items
from benchmarks.informalizer.client import (
    Journal,
    Request,
    parse_temperature,
    prompt_digest,
    usage_fields,
)
from benchmarks.informalizer.estimate_cost import Price, generation_cost
from benchmarks.informalizer.score_cost import journal_totals, mathlib_estimate


def test_journal_resumes_only_identical_answered_prompts(tmp_path):
    """Journal resumes only identical answered prompts."""
    request = Request(key="declaration:A", kind="declaration", module="M", prompt="p")
    journal = Journal(tmp_path / "journal.jsonl")
    journal.append({"key": "declaration:A", "content": None, "error": "timeout"})
    assert journal.answered(request) is None
    journal.append(
        {"key": "declaration:A", "content": "x", "prompt_sha256": prompt_digest("p")}
    )
    reopened = Journal(tmp_path / "journal.jsonl")
    assert reopened.answered(request)["content"] == "x"
    changed = Request(key="declaration:A", kind="declaration", module="M", prompt="q")
    assert reopened.answered(changed) is None


def test_usage_reads_openrouter_extras():
    """Usage reads openrouter extras."""
    usage = CompletionUsage.model_validate(
        {
            "prompt_tokens": 10,
            "completion_tokens": 5,
            "total_tokens": 15,
            "completion_tokens_details": {"reasoning_tokens": 3},
            "prompt_tokens_details": {"cached_tokens": 4},
            "cost": 0.002,
        }
    )
    fields = usage_fields(usage)
    assert fields["reasoning_tokens"] == 3 and fields["cached_tokens"] == 4
    assert fields["cost"] == 0.002
    assert parse_temperature("none") is None and parse_temperature("0.3") == 0.3


def test_batch_prompt_lists_names_with_notes():
    """Batch prompt lists names with notes."""
    batch = {
        "items": [
            {"name": "A.mul_c", "kind": "theorem", "note": None},
            {
                "name": "A.add_c",
                "kind": "theorem",
                "note": "generated by @[to_additive]",
            },
        ],
        "excerpt": "theorem mul_c : {x} = x",
        "context": [],
    }
    items = render_items(batch["items"])
    assert items.splitlines()[1] == "- A.add_c (theorem; generated by @[to_additive])"
    prompt = render_batch(batch, "{items}|{excerpt}|{context}")
    assert prompt.endswith("|theorem mul_c : {x} = x|None.")


def test_costs_are_summed_and_weighted_by_stratum():
    """Costs are summed and weighted by stratum."""
    records = [
        {
            "kind": "batch",
            "module": "M0",
            "content": "x",
            "cost": 1.0,
            "prompt_tokens": 10,
            "started": 0.0,
            "elapsed_seconds": 2.0,
        },
        {
            "kind": "batch",
            "module": "M1",
            "content": None,
            "cost": None,
            "started": 1.0,
            "elapsed_seconds": 5.0,
        },
    ]
    totals = journal_totals(records, {"M0": 0, "M1": 1})
    assert totals["failed"] == 1 and totals["calls_without_cost"] == 1
    assert totals["wall_seconds"] == 6.0
    strata = [{"index": 0, "declarations": 100}, {"index": 1, "declarations": 50}]
    estimate = mathlib_estimate({0: 1.0, 1: 2.0}, Counter({0: 10, 1: 5}), strata)
    assert estimate == 10.0 + 20.0


def test_prefix_caching_applies_above_the_provider_minimum():
    """Prefix caching applies above the provider minimum."""
    estimate = {"overall": {"requests": 10, "input_tokens": 10_000, "output_tokens": 0}}
    price = Price(1.0, 1.0, 0.1, cache_minimum=500)
    assert generation_cost(estimate, price, 0, 600, cached=True) == (4_000 + 600) / 1e6
    assert generation_cost(estimate, price, 0, 400, cached=True) == 10_000 / 1e6
