//! Python bindings: `lean_source_parser._native`.

use lean_source::keywords::Modifier;
use lean_source::pos::LineIndex;
use lean_source::refs::{Project, References, SourceFile};
use lean_source::{Parsed, Span};
use pyo3::exceptions::PyValueError;
use pyo3::prelude::*;
use pyo3::types::{PyDict, PyList};
use rayon::prelude::*;

type SpanTuple = (u32, u32, u32, u32, u32, u32);
type ParsedFile = std::io::Result<(Vec<u8>, Parsed)>;
/// The parsed files of a project and the context files with their sources.
type ParsedProject = (Vec<ParsedFile>, Vec<(Vec<u8>, Parsed)>);

fn span(src: &[u8], idx: &LineIndex, s: Span) -> SpanTuple {
    let a = idx.pos(src, s.start);
    let b = idx.pos(src, s.end);
    (a.byte, a.line, a.col, b.byte, b.line, b.col)
}

fn slice(src: &[u8], s: Span) -> &str {
    std::str::from_utf8(&src[s.start as usize..s.end as usize]).unwrap_or("")
}

fn decls_to_py<'py>(
    py: Python<'py>,
    src: &[u8],
    parsed: &Parsed,
    file: &str,
    module: &str,
    text: bool,
    references: Option<&[References<'_>]>,
) -> PyResult<Bound<'py, PyList>> {
    let idx = LineIndex::new(src);
    let out = PyList::empty(py);
    for (i, d) in parsed.decls.iter().enumerate() {
        let o = PyDict::new(py);
        o.set_item("file", file)?;
        o.set_item("module", module)?;
        o.set_item("index", i)?;
        o.set_item("kind", d.kind.as_str())?;
        o.set_item("name", d.name.as_deref())?;
        o.set_item("generated", d.generated)?;
        o.set_item("approximate", d.approximate)?;
        o.set_item("origin", d.origin.map(|s| slice(src, s)))?;
        o.set_item("parent", d.parent)?;
        let mods: Vec<&str> = Modifier::ALL
            .iter()
            .filter(|m| d.modifiers & m.bit() != 0)
            .map(|m| m.name())
            .collect();
        o.set_item("modifiers", mods)?;
        let attrs: Vec<&str> = parsed.attrs[d.attrs.0 as usize..d.attrs.1 as usize]
            .iter()
            .map(|a| slice(src, a.span))
            .collect();
        o.set_item("attributes", attrs)?;
        o.set_item("range", span(src, &idx, d.range))?;
        o.set_item("selection", span(src, &idx, d.selection))?;
        o.set_item("signature", span(src, &idx, d.signature))?;
        o.set_item("type", d.type_.map(|s| span(src, &idx, s)))?;
        o.set_item("body", d.body.map(|s| span(src, &idx, s)))?;
        o.set_item("doc", d.doc.map(|s| span(src, &idx, s)))?;
        if text {
            o.set_item("text", slice(src, d.range))?;
            o.set_item("signature_text", slice(src, d.signature))?;
            o.set_item("type_text", d.type_.map(|s| slice(src, s)))?;
            o.set_item("doc_text", d.doc.map(|s| slice(src, s)))?;
        }
        if let Some(found) = references.and_then(|all| all.get(i)) {
            o.set_item("references", PyList::new(py, found.names.iter().copied())?)?;
            let in_type = found.names.iter().zip(&found.in_type);
            let names = in_type
                .filter(|(_, in_type)| **in_type)
                .map(|(name, _)| *name);
            o.set_item("type_references", PyList::new(py, names)?)?;
        }
        out.append(o)?;
    }
    Ok(out)
}

/// Parses Lean source text and returns one dict per declaration.
///
/// Spans are tuples `(start_byte, start_line, start_col, end_byte, end_line, end_col)`, with
/// 1-based lines and columns in code points, as Lean reports them. With `text=True` each dict
/// also carries the source of the declaration, its signature, type and doc comment.
#[pyfunction]
#[pyo3(signature = (source, file = "", module = "", text = false))]
fn parse<'py>(
    py: Python<'py>,
    source: &str,
    file: &str,
    module: &str,
    text: bool,
) -> PyResult<Bound<'py, PyList>> {
    let parsed = py.detach(|| lean_source::parse(source.as_bytes()));
    decls_to_py(py, source.as_bytes(), &parsed, file, module, text, None)
}

/// File name and module name of `path` relative to `root`: `Mathlib/Data/Nat.lean` gives
/// `Mathlib.Data.Nat`.
fn module_of(path: &std::path::Path, root: Option<&std::path::Path>) -> (String, String) {
    let rel = match root {
        Some(r) => path.strip_prefix(r).unwrap_or(path),
        None => path,
    };
    let file = rel.to_string_lossy().into_owned();
    let module = rel
        .with_extension("")
        .components()
        .map(|c| c.as_os_str().to_string_lossy().into_owned())
        .collect::<Vec<_>>()
        .join(".");
    (file, module)
}

/// Parses several files in parallel, without the GIL, as one project: names generated by
/// `to_additive` and `to_dual` are resolved against the other files. Returns one list of
/// declaration dicts per path, in order. Module names are relative to `root` when it is given.
/// `context_paths` supplies imported Lean files for name and field resolution without emitting
/// their declarations. A missing context file is an error.
///
/// With `references=True` each declaration dict also has `"references"`: the full names its
/// signature refers to, in order of first appearance, among the declarations of `paths`, of
/// `context_paths` and `known_names` (names declared elsewhere, such as in the project's
/// dependencies). They are the identifiers resolved by Lean's lookup rules, the constants
/// that notations declared in `paths` or `context_paths` stand for, and the fields of terms
/// whose type is written. `"type_references"` are the ones written in the type after the
/// signature's colon. A context file takes part in the modules that import it, so its path
/// must end with its module name; every file imports `Init`. The list includes names that
/// only shadow others, such as private declarations and structure fields, and can include
/// the declaration's own name. `include_approximate` lets names that a naming rule derived
/// be referred to as well.
#[pyfunction]
#[pyo3(signature = (
    paths,
    root = None,
    text = false,
    context_paths = None,
    references = false,
    known_names = None,
    include_approximate = false,
))]
#[allow(clippy::too_many_arguments)]
fn parse_files<'py>(
    py: Python<'py>,
    paths: Vec<std::path::PathBuf>,
    root: Option<std::path::PathBuf>,
    text: bool,
    context_paths: Option<Vec<std::path::PathBuf>>,
    references: bool,
    known_names: Option<Vec<String>>,
    include_approximate: bool,
) -> PyResult<Bound<'py, PyList>> {
    let context_paths = context_paths.unwrap_or_default();
    let (results, context) = py
        .detach(|| -> std::io::Result<ParsedProject> {
            let context: Vec<(Vec<u8>, Parsed)> = context_paths
                .par_iter()
                .map(|path| {
                    std::fs::read(path)
                        .map(|src| {
                            let parsed = lean_source::parse(&src);
                            (src, parsed)
                        })
                        .map_err(|err| {
                            std::io::Error::new(err.kind(), format!("{}: {err}", path.display()))
                        })
                })
                .collect::<std::io::Result<_>>()?;
            let first: Vec<std::io::Result<(Vec<u8>, Parsed)>> = paths
                .par_iter()
                .map(|p| {
                    let src = std::fs::read(p)?;
                    let parsed = lean_source::parse(&src);
                    Ok((src, parsed))
                })
                .collect();
            if paths.len() < 2 && context.is_empty() {
                return Ok((first, context));
            }
            // Imported structure fields and attribute translations may come from context files.
            let ctx = lean_source::Context::build(
                context
                    .iter()
                    .map(|(_, parsed)| parsed)
                    .chain(first.iter().filter_map(|r| r.as_ref().ok().map(|(_, p)| p))),
                false,
            );
            let again = first
                .into_par_iter()
                .map(|r| {
                    r.map(|(src, parsed)| {
                        let uses = parsed.needs_simps_context
                            || parsed.needs_structure_context
                            || parsed.decls.iter().any(|d| d.origin.is_some());
                        if uses {
                            let again = lean_source::parse_in(&src, &ctx);
                            (src, again)
                        } else {
                            (src, parsed)
                        }
                    })
                })
                .collect();
            Ok((again, context))
        })
        .map_err(|err| PyValueError::new_err(err.to_string()))?;
    let mut files = Vec::with_capacity(paths.len());
    for (p, r) in paths.iter().zip(results) {
        let (src, parsed) =
            r.map_err(|e| PyValueError::new_err(format!("{}: {e}", p.display())))?;
        let (file, module) = module_of(p, root.as_deref());
        files.push((file, module, src, parsed));
    }
    let known_names = known_names.unwrap_or_default();
    // A context file is named by its whole path, which ends with its module name.
    let modules: Vec<String> = context_paths
        .iter()
        .map(|path| module_of(path, None).1)
        .collect();
    let resolved = references.then(|| {
        py.detach(|| {
            let sources: Vec<SourceFile> = files
                .iter()
                .map(|(_, module, src, parsed)| SourceFile {
                    module,
                    source: src,
                    parsed,
                })
                .collect();
            let context: Vec<SourceFile> = context
                .iter()
                .zip(&modules)
                .map(|((src, parsed), module)| SourceFile {
                    module,
                    source: src,
                    parsed,
                })
                .collect();
            Project::with_context(&sources, &context, &known_names, include_approximate)
                .detailed_references()
        })
    });
    let out = PyList::empty(py);
    for (index, (file, module, src, parsed)) in files.iter().enumerate() {
        let names = resolved.as_ref().map(|all| all[index].as_slice());
        out.append(decls_to_py(py, src, parsed, file, module, text, names)?)?;
    }
    Ok(out)
}

/// Commands of a file: `kind`, `range`, `head` and the namespace in effect.
#[pyfunction]
fn commands<'py>(py: Python<'py>, source: &str) -> PyResult<Bound<'py, PyList>> {
    let src = source.as_bytes();
    let parsed = py.detach(|| lean_source::parse(src));
    let idx = LineIndex::new(src);
    let out = PyList::empty(py);
    for c in &parsed.commands {
        let o = PyDict::new(py);
        o.set_item("kind", c.kind.as_str())?;
        o.set_item("range", span(src, &idx, c.range))?;
        o.set_item("head", slice(src, c.head))?;
        o.set_item("namespace", &parsed.namespaces[c.namespace as usize])?;
        out.append(o)?;
    }
    Ok(out)
}

#[pymodule]
fn _native(m: &Bound<'_, PyModule>) -> PyResult<()> {
    m.add_function(wrap_pyfunction!(parse, m)?)?;
    m.add_function(wrap_pyfunction!(parse_files, m)?)?;
    m.add_function(wrap_pyfunction!(commands, m)?)?;
    Ok(())
}
