use lean_informal::context::{self, ContextLine};
use lean_informal::input::{ContextEntry, Knowledge, Target};
use lean_informal::plan::{Budget, Route, alias_source, plan_file};
use lean_informal::scope;

const SOURCE: &str = r#"import Mathlib.Foo
/-! # Module doc -/
open Function
namespace Foo
variable {G : Type*} [Group G]
section Sub
variable (x : G)
local notation "𝔾" => G
open Bar in
theorem a : x * 1 = x := by simp
omit [Group G] in
lemma b (y : G) : True := trivial
variable (z : G) in
@[to_additive (attr := simp)] theorem mul_c : z = z := rfl
end Sub
include x
instance : Inhabited G := ⟨1⟩
alias a2 := a
@[reassoc] lemma d : f ≫ g = h := sorry
def e : ℕ := 3
end Foo
"#;

fn target(name: &str, line: u32, dependencies: &[&str]) -> Target {
    Target {
        name: name.to_string(),
        module: "Mathlib.Test".to_string(),
        path: Some("Mathlib/Test.lean".to_string()),
        start_line: Some(line),
        dependencies: dependencies.iter().map(|d| d.to_string()).collect(),
    }
}

fn targets() -> Vec<Target> {
    vec![
        target("Foo.a", 10, &["Rare.thing", "Eq"]),
        target("Foo.b", 12, &["Rare.thing"]),
        target("Foo.mul_c", 14, &[]),
        target("Foo.add_c", 14, &[]),
        target("Foo.instInhabited", 17, &[]),
        target("Foo.a2", 18, &[]),
        target("Foo.d", 19, &[]),
        target("Foo.d_assoc", 19, &[]),
        target("Foo.e", 20, &[]),
    ]
}

fn knowledge(targets: &[Target]) -> Knowledge {
    let entry = |name: &str, frequency| ContextEntry {
        name: name.to_string(),
        description: Some(format!("**{name}.** A description.")),
        frequency,
    };
    Knowledge {
        context: [entry("Rare.thing", 3), entry("Eq", 90000)]
            .into_iter()
            .map(|e| (e.name.clone(), e))
            .collect(),
        common: ["Eq".to_string()].into_iter().collect(),
        targets: targets
            .iter()
            .map(|t| (t.name.clone(), t.clone()))
            .collect(),
    }
}

#[test]
fn scope_tracks_frames_and_in_prefixes() {
    let parsed = lean_source::parse(SOURCE.as_bytes());
    let units = scope::units(SOURCE.as_bytes(), &parsed, |_| true);
    let first = &units[0];
    assert_eq!(parsed.decls[first.decl].name.as_deref(), Some("Foo.a"));
    assert_eq!(
        first.scope,
        [
            "open Function",
            "namespace Foo",
            "variable {G : Type*} [Group G]",
            "section Sub",
            "variable (x : G)",
            "local notation \"𝔾\" => G",
        ]
    );
    assert_eq!(first.prefix, ["open Bar in"]);
    assert_eq!(units[1].prefix, ["omit [Group G] in"]);
    assert_eq!(units[1].between, ["omit [Group G] in"]);
    let instance = units
        .iter()
        .find(|unit| parsed.decls[unit.decl].kind.as_str() == "instance")
        .unwrap();
    assert_eq!(
        instance.scope,
        [
            "open Function",
            "namespace Foo",
            "variable {G : Type*} [Group G]",
            "include x"
        ]
    );
    assert_eq!(instance.between, ["end Sub", "include x"]);
}

#[test]
fn plan_routes_aliases_and_reassoc_lemmas() {
    let targets = targets();
    let knowledge = knowledge(&targets);
    let references: Vec<&Target> = targets.iter().collect();
    let plan = plan_file(
        "Mathlib/Test.lean",
        "Mathlib.Test",
        SOURCE.as_bytes(),
        &references,
        &knowledge,
        &Budget::default(),
    );
    assert!(plan.unmatched.is_empty(), "{:?}", plan.unmatched);
    let route = |name: &str, rule: &str, from: &str| Route {
        name: name.to_string(),
        rule: rule.to_string(),
        from: from.to_string(),
    };
    assert_eq!(
        plan.routes,
        [
            route("Foo.a2", "alias", "Foo.a"),
            route("Foo.d_assoc", "reassoc", "Foo.d")
        ]
    );
    assert_eq!(plan.batches.len(), 1);
    let batch = &plan.batches[0];
    let names: Vec<&str> = batch.items.iter().map(|i| i.name.as_str()).collect();
    assert_eq!(
        names,
        [
            "Foo.a",
            "Foo.b",
            "Foo.mul_c",
            "Foo.add_c",
            "Foo.instInhabited",
            "Foo.d",
            "Foo.e"
        ]
    );
    let twin = &batch.items[3];
    assert_eq!(
        twin.note.as_deref(),
        Some("generated by @[to_additive] from Foo.mul_c")
    );
    assert!(batch.excerpt.contains("theorem a : x * 1 = x\n"));
    assert!(!batch.excerpt.contains("by simp"));
    assert!(batch.excerpt.contains("def e : ℕ := 3"));
    assert!(batch.excerpt.contains("open Bar in\ntheorem a"));
    assert_eq!(
        batch.context,
        [ContextLine {
            name: "Rare.thing".to_string(),
            description: "**Rare.thing.** A description.".to_string(),
        }]
    );
}

#[test]
fn a_new_request_opens_with_the_scope_in_effect() {
    let targets = targets();
    let knowledge = knowledge(&targets);
    let references: Vec<&Target> = targets.iter().collect();
    let budget = Budget {
        batch_items: 2,
        ..Budget::default()
    };
    let plan = plan_file(
        "Mathlib/Test.lean",
        "Mathlib.Test",
        SOURCE.as_bytes(),
        &references,
        &knowledge,
        &budget,
    );
    assert!(plan.batches.iter().all(|batch| batch.items.len() <= 2));
    let second = &plan.batches[1];
    assert_eq!(second.id, "Mathlib/Test.lean#1");
    assert!(second.excerpt.starts_with(
        "open Function\nnamespace Foo\nvariable {G : Type*} [Group G]\nsection Sub\n"
    ));
}

#[test]
fn unknown_names_are_left_to_the_fallback() {
    let targets = vec![target("Foo.nowhere", 2, &[])];
    let knowledge = knowledge(&targets);
    let references: Vec<&Target> = targets.iter().collect();
    let plan = plan_file(
        "Mathlib/Test.lean",
        "Mathlib.Test",
        SOURCE.as_bytes(),
        &references,
        &knowledge,
        &Budget::default(),
    );
    assert!(plan.batches.is_empty());
    assert_eq!(plan.unmatched[0].name, "Foo.nowhere");
}

#[test]
fn alias_targets_resolve_from_the_innermost_namespace() {
    let targets = vec![target("A.B.x", 1, &[]), target("A.y", 1, &[])];
    let knowledge = knowledge(&targets);
    assert_eq!(
        alias_source("alias z := x", "A.B.z", &knowledge),
        Some("A.B.x".to_string())
    );
    assert_eq!(
        alias_source("alias z := y", "A.B.z", &knowledge),
        Some("A.y".to_string())
    );
    assert_eq!(
        alias_source("alias z := Rare.thing", "A.B.z", &knowledge),
        Some("Rare.thing".to_string())
    );
    assert_eq!(
        alias_source("alias ⟨mp, mpr⟩ := x", "A.B.mp", &knowledge),
        None
    );
    assert_eq!(
        alias_source("alias z := missing", "A.B.z", &knowledge),
        None
    );
    assert_eq!(
        alias_source(
            "@[deprecated (since := \"2026-01-16\")] alias z := x",
            "A.B.z",
            &knowledge
        ),
        Some("A.B.x".to_string())
    );
}

#[test]
fn context_prefers_shared_then_rare_dependencies() {
    let mut targets = vec![
        target("T.one", 1, &["Shared", "Rare", "Common", "T.two"]),
        target("T.two", 2, &["Shared", "Often"]),
    ];
    targets.push(target("T.three", 3, &[]));
    let mut knowledge = knowledge(&targets);
    for (name, frequency) in [("Shared", 500), ("Rare", 2), ("Often", 4000), ("Common", 1)] {
        knowledge.context.insert(
            name.to_string(),
            ContextEntry {
                name: name.to_string(),
                description: Some("x".repeat(400)),
                frequency,
            },
        );
    }
    knowledge.common.insert("Common".to_string());
    let items = vec!["T.one".to_string(), "T.two".to_string()];
    let selection = context::select(&items, &knowledge, 10_000, 256);
    let names: Vec<&str> = selection.lines.iter().map(|l| l.name.as_str()).collect();
    assert_eq!(names, ["Shared", "Rare", "Often"]);
    assert_eq!(selection.lines[0].description.chars().count(), 256);
    assert!(selection.lines[0].description.ends_with("..."));
    let tight = context::select(&items, &knowledge, 100, 256);
    assert_eq!(tight.lines.len(), 1);
    assert_eq!(tight.dropped, 2);
}

#[test]
fn references_carry_the_scope_and_the_parent_statement() {
    let targets = targets();
    let references_list: Vec<&Target> = targets.iter().collect();
    let found = lean_informal::plan::references(
        "Mathlib/Test.lean",
        "Mathlib.Test",
        SOURCE.as_bytes(),
        &references_list,
    );
    assert_eq!(found.len(), targets.len());
    let twin = found.iter().find(|r| r.name == "Foo.add_c").unwrap();
    assert!(twin.statement.ends_with("theorem mul_c : z = z"));
    assert_eq!(twin.scope.last().unwrap(), "variable (z : G) in");
    assert_eq!(
        twin.note.as_deref(),
        Some("generated by @[to_additive] from Foo.mul_c")
    );
    let first = found.iter().find(|r| r.name == "Foo.a").unwrap();
    assert!(first.scope.contains(&"variable (x : G)".to_string()));
    assert_eq!(first.statement, "theorem a : x * 1 = x");
}
