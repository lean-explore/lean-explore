"""Generate `translate_tables.rs` from Mathlib's translation dictionaries.

Usage:
    python3 tools/gen_translate_tables.py MATHLIB_DIR \
        > crates/lean-source/src/translate_tables.rs

Reads `nameDict` and `abbreviationDict` from ToAdditive.lean and ToDual.lean in
Mathlib/Tactic/Translate. Regenerate when Mathlib changes them.
"""

import pathlib
import re
import subprocess
import sys

root = pathlib.Path(sys.argv[1])
TUPLE_LIST = re.compile(r'\(\s*"((?:[^"\\]|\\.)*)"\s*,\s*\[([^\]]*)\]\s*\)')
TUPLE_STR = re.compile(r'\(\s*"((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"\s*\)')


def block(text, name):
    """Return the list literal of the `.ofList [...]` that defines `name`."""
    start = text.index(f"def {name}")
    start = text.index(".ofList [", start) + len(".ofList [")
    depth, i = 1, start
    while depth:
        c = text[i]
        if c == "[":
            depth += 1
        elif c == "]":
            depth -= 1
        elif c == "-" and text[i + 1] == "-":
            i = text.index("\n", i)
        elif c == '"':
            i = text.index('"', i + 1)
        i += 1
    body = text[start : i - 1]
    return "\n".join(
        line.split("--")[0] if '"' not in line.split("--")[0][-1:] else line
        for line in body.split("\n")
    )


def rust_str(s):
    """Quote `s` as a Rust string literal."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


try:
    rev = subprocess.run(
        ["git", "-C", str(root), "rev-parse", "HEAD"], capture_output=True, text=True
    ).stdout.strip()
except OSError:
    rev = "unknown"
print(
    "//! `to_additive` and `to_dual` dictionaries, generated by "
    "`tools/gen_translate_tables.py` from"
)
print(f"//! Mathlib {rev[:12]} (Mathlib/Tactic/Translate). Do not edit.")
for attr, file in (("ADDITIVE", "ToAdditive.lean"), ("DUAL", "ToDual.lean")):
    text = (root / "Mathlib/Tactic/Translate" / file).read_text(encoding="utf-8")
    names = TUPLE_LIST.findall(block(text, "nameDict"))
    abbrevs = TUPLE_STR.findall(block(text, "abbreviationDict"))
    print()
    print(f"pub static {attr}_NAMES: &[(&str, &[&str])] = &[")
    for k, v in names:
        parts = re.findall(r'"((?:[^"\\]|\\.)*)"', v)
        print(f"    ({rust_str(k)}, &[{', '.join(rust_str(p) for p in parts)}]),")
    print("];")
    print()
    print(f"pub static {attr}_ABBREVIATIONS: &[(&str, &str)] = &[")
    for k, v in abbrevs:
        print(f"    ({rust_str(k)}, {rust_str(v)}),")
    print("];")
